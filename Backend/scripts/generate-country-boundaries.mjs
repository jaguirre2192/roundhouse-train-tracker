// Usage: node scripts/generate-country-boundaries.mjs /path/to/ne_10m_admin_0_countries.geojson
// Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

if (!process.argv[2]) throw new Error("Supply the Natural Earth 1:10m countries GeoJSON file");
const raw = await readFile(process.argv[2]);
const features = JSON.parse(raw.toString("utf8")).features;
// Correct physical station countries on the reproduced cross-border corridors.
// Include neighboring countries on those routes so the correction works in both directions.
const selected = new Map([
  ["FRA", "FR"], ["BEL", "BE"], ["NLD", "NL"], ["ESP", "ES"],
  ["AZE", "AZ"], ["HUN", "HU"], ["LIE", "LI"], ["LUX", "LU"],
  ["LVA", "LV"], ["MCO", "MC"], ["SRB", "RS"], ["SVK", "SK"], ["UKR", "UA"],
  ["AUT", "AT"], ["CHE", "CH"], ["DEU", "DE"], ["ITA", "IT"],
  ["LTU", "LT"], ["MNE", "ME"], ["GEO", "GE"], ["ROU", "RO"],
  ["DNK", "DK"], ["SWE", "SE"], ["SVN", "SI"],
]);
const countries = [];
for (const feature of features) {
  const countryCode = selected.get(feature.properties.ADM0_A3);
  if (!countryCode) continue;
  const rawPolygons = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  const polygons = rawPolygons.flatMap((rings) => {
    const points = rings[0];
    const bounds = [Math.min(...points.map((p) => p[0])), Math.min(...points.map((p) => p[1])),
      Math.max(...points.map((p) => p[0])), Math.max(...points.map((p) => p[1]))];
    // Restrict this correction table to Europe/Caucasus territory, preserving other
    // countries/territories' explicit metadata and existing fallback behavior.
    return bounds[0] >= -12 && bounds[1] >= 35 && bounds[2] <= 52 && bounds[3] <= 72 ? [{ bounds, rings }] : [];
  });
  countries.push({ countryCode, polygons });
}
if (countries.length !== selected.size || countries.some((country) => country.polygons.length === 0)) throw new Error("Missing expected country boundaries");
const header = `// Generated by scripts/generate-country-boundaries.mjs; do not edit coordinates.
// Natural Earth 1:10m Admin 0 Countries, selected Europe/Caucasus territory; public domain.
// https://www.naturalearthdata.com/about/terms-of-use/
// Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson
// Source SHA-256: ${createHash("sha256").update(raw).digest("hex")}
export type BoundaryPoint = readonly [longitude: number, latitude: number];
export interface CountryPolygon {
  bounds: readonly [west: number, south: number, east: number, north: number];
  rings: readonly (readonly BoundaryPoint[])[];
}
export const countryBoundaries: readonly { countryCode: string; polygons: readonly CountryPolygon[] }[] = [
`;
await writeFile(new URL("../src/providers/country-boundaries.generated.ts", import.meta.url),
  header + countries.map((value) => JSON.stringify(value)).join(",\n") + "\n];\n");
console.log(JSON.stringify({ countries: countries.map((value) => value.countryCode),
  polygons: countries.reduce((total, value) => total + value.polygons.length, 0) }));
